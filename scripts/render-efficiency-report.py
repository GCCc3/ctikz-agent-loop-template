#!/usr/bin/env python3
"""Render a validated efficiency analysis result as deterministic Markdown.

usage: render-efficiency-report.py ANALYSIS.json [OUTPUT.md]

The output path defaults to the input path with a .md suffix. Rendering is a
pure function of the JSON so the report can be regenerated byte-identically.
"""
import json
import sys
from pathlib import Path


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def render(report):
    scope = report["scope"]
    iterations = scope["iterationsReviewed"]
    span = "none" if not iterations else (
        f"iteration {iterations[0]}" if len(iterations) == 1
        else f"iterations {iterations[0]}–{iterations[-1]}"
    )
    out = []
    out.append(f"# Efficiency analysis — {span}")
    out.append("")
    out.append(f"- status: `{report['status']}`")
    out.append(f"- iterations reviewed: {', '.join(str(i) for i in iterations) or 'none'}")
    if report["blocker"]:
        out.append(f"- blocker: {report['blocker']}")
    out.append("")
    out.append("## Summary")
    out.append("")
    out.append(report["summary"])
    out.append("")

    out.append("## Artifacts inspected")
    out.append("")
    if scope["artifactsInspected"]:
        for artifact in scope["artifactsInspected"]:
            out.append(f"- `{artifact}`")
    else:
        out.append("_none recorded_")
    out.append("")

    out.append("## Patterns")
    out.append("")
    if report["patterns"]:
        out.append("| id | confidence | occurrences | pattern |")
        out.append("|---|---|---|---|")
        for pattern in report["patterns"]:
            out.append(
                f"| {cell(pattern['id'])} | {cell(pattern['confidence'])} | "
                f"{len(pattern['occurrences'])} | {cell(pattern['description'])} |"
            )
        out.append("")
        for pattern in report["patterns"]:
            out.append(f"### {pattern['id']} — {pattern['description']}")
            out.append("")
            out.append(f"Generalisation: {pattern['generalization']}")
            out.append("")
            if pattern["occurrences"]:
                out.append("Occurrences:")
                out.append("")
                for occ in pattern["occurrences"]:
                    out.append(
                        f"- iteration {occ['iteration']} · {occ['agent']} · {occ['evidence']}"
                    )
            else:
                out.append("_no occurrences recorded — pattern is unsubstantiated_")
            out.append("")
    else:
        out.append("_no repeatable patterns found_")
        out.append("")

    out.append("## Tool proposals")
    out.append("")
    if report["toolProposals"]:
        for proposal in report["toolProposals"]:
            out.append(f"### `{proposal['name']}` (confidence: {proposal['confidence']})")
            out.append("")
            out.append(f"- purpose: {proposal['purpose']}")
            out.append(f"- patterns addressed: {', '.join(proposal['patternIds']) or 'none'}")
            out.append(f"- expected savings: {proposal['expectedSavings']}")
            out.append(f"- risks: {proposal['risks']}")
            out.append("")
            out.append("Proposed tool description:")
            out.append("")
            out.append("> " + proposal["description"].replace("\n", "\n> "))
            out.append("")
            if proposal["inputs"]:
                out.append("| input | type | required | description |")
                out.append("|---|---|---|---|")
                for arg in proposal["inputs"]:
                    out.append(
                        f"| {cell(arg['name'])} | {cell(arg['type'])} | "
                        f"{'yes' if arg['required'] else 'no'} | {cell(arg['description'])} |"
                    )
                out.append("")
            else:
                out.append("_no inputs_")
                out.append("")
            out.append(f"Outputs: {proposal['outputs']}")
            out.append("")
    else:
        out.append("_no tool proposals_")
        out.append("")

    out.append("## Non-tool recommendations")
    out.append("")
    if report["nonToolRecommendations"]:
        for item in report["nonToolRecommendations"]:
            out.append(f"- {item['description']}")
            out.append(f"  - rationale: {item['rationale']}")
            out.append(f"  - expected savings: {item['expectedSavings']}")
    else:
        out.append("_none_")
    out.append("")

    out.append("## Rejected patterns")
    out.append("")
    if report["rejectedPatterns"]:
        for item in report["rejectedPatterns"]:
            out.append(f"- {item['description']}")
            out.append(f"  - why not generalised: {item['reason']}")
    else:
        out.append("_none_")
    out.append("")

    out.append("## Open questions")
    out.append("")
    if report["openQuestions"]:
        for question in report["openQuestions"]:
            out.append(f"- {question}")
    else:
        out.append("_none_")
    out.append("")
    return "\n".join(out)


def main():
    if len(sys.argv) not in (2, 3):
        print("usage: render-efficiency-report.py ANALYSIS.json [OUTPUT.md]", file=sys.stderr)
        return 2
    src = Path(sys.argv[1])
    dst = Path(sys.argv[2]) if len(sys.argv) == 3 else src.with_suffix(".md")
    try:
        report = json.loads(src.read_text(encoding="utf-8"))
        text = render(report)
    except Exception as exc:
        print(f"render failed: {exc}", file=sys.stderr)
        return 1
    dst.write_text(text, encoding="utf-8")
    print(f"rendered {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
